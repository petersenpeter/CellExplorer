function [section,controls]=buildTraceSection(parent,settings,callbacks)
%BUILDTRACESECTION Define trace controls; RowSection owns all their geometry.
section=ce.ui.layout.RowSection(parent,'Extracellular traces',settings.fontsize);
controls.filter=section.Panel;
controls.plotStyle=section.addField('plotStyle','Plot style','popupmenu', ...
    'String',{'Downsampled','Range','Raw','LFP (*.lfp file)','Image','No ephys traces'}, ...
    'Value',settings.plotStyle,'Callback',callbacks.changePlotStyle);
controls.colorScale=section.addField('colorScale','Plot colors','popupmenu', ...
    'String',{'Colors','Colors 75%','Colors 50%','Colors 25%','Grey-scale','Grey-scale 75%','Grey-scale 50%','Grey-scale 25%'}, ...
    'Value',1,'Callback',callbacks.changeColorScale);
pair=section.addRow('filterOptions', ...
    {'Style','checkbox','String','Filter traces','Value',0,'Callback',callbacks.changeTraceFilter}, ...
    {'Style','checkbox','String','Group spacing','Value',settings.extraSpacing,'Callback',callbacks.extraSpacing});
controls.filterToggle=pair(1); controls.extraSpacing=pair(2);
controls.lowerBand=section.addField('lowerBand','Lower filter (Hz)','edit','String','400', ...
    'Callback',callbacks.changeTraceFilter,'TooltipString','Lower frequency boundary (Hz)');
controls.higherBand=section.addField('higherBand','Higher filter (Hz)','edit','String','', ...
    'Callback',callbacks.changeTraceFilter,'TooltipString','Higher frequency boundary (Hz)');
pair=section.addRow('energy', ...
    {'Style','checkbox','String','Absolute smoothing (s)','Value',0,'Callback',callbacks.plotEnergy}, ...
    {'Style','edit','String',num2str(settings.energyWindow),'Callback',callbacks.plotEnergy,'TooltipString','Smoothing window (seconds)'});
controls.plotEnergy=pair(1); controls.energyWindow=pair(2);
pair=section.addRow('events', ...
    {'Style','checkbox','String',['Detect events (',char(181),'V)'],'Value',0,'Callback',callbacks.toogleDetectEvents}, ...
    {'Style','edit','String',num2str(settings.eventThreshold),'Callback',callbacks.toogleDetectEvents,'TooltipString','Event detection threshold (microvolts)'});
controls.detectEvents=pair(1); controls.eventThreshold=pair(2);
pair=section.addRow('spikes', ...
    {'Style','checkbox','String',['Detect spikes (',char(181),'V)'],'Value',0,'Callback',callbacks.toogleDetectSpikes}, ...
    {'Style','edit','String',num2str(settings.spikesDetectionThreshold),'Callback',callbacks.toogleDetectSpikes,'TooltipString','Spike detection threshold (microvolts)'});
controls.detectSpikes=pair(1); controls.detectThreshold=pair(2);
end
