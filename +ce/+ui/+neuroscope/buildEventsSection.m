function [section,controls]=buildEventsSection(parent,settings,callbacks)
%BUILDEVENTSSECTION Event controls retain their callbacks and metadata contract.
section=ce.ui.layout.RowSection(parent,'Event controls',settings.fontsize);
controls.main=section.Panel;
pair=section.addRow('display', ...
    {'Style','checkbox','String','Intervals','Value',0,'Callback',callbacks.showEventsIntervals,'KeyPressFcn',callbacks.keyPress,'TooltipString','Show event intervals'}, ...
    {'Style','checkbox','String','Processing','Value',0,'Callback',callbacks.processing_steps,'KeyPressFcn',callbacks.keyPress,'TooltipString','Show event processing steps'});
controls.showEventsIntervals=pair(1); controls.processing_steps=pair(2);
controls.eventNumber=section.addField('eventNumber','Event number','edit','String','', ...
    'HorizontalAlignment','center','Callback',callbacks.gotoEvents,'TooltipString','Jump to event number');
controls.eventCount=section.addField('eventCount','Total events','edit','String','nEvents','Enable','off','HorizontalAlignment','center');
buttons=section.addButtons('browse',{
    {'String',char(8592),'Callback',callbacks.previousEvent,'KeyPressFcn',callbacks.keyPress,'TooltipString','Previous event'}, ...
    {'String','Random','Callback',callbacks.randomEvent,'KeyPressFcn',callbacks.keyPress,'TooltipString','Random event'}, ...
    {'String',char(8594),'Callback',callbacks.nextEvent,'KeyPressFcn',callbacks.keyPress,'TooltipString','Next event'}});
controls.previousEvent=buttons(1); controls.randomEvent=buttons(2); controls.nextEvent=buttons(3);
pair=section.addRow('flag', ...
    {'Style','pushbutton','String','Flag event','Callback',callbacks.flagEvent,'KeyPressFcn',callbacks.keyPress,'TooltipString','Flag selected event'}, ...
    {'Style','edit','String','nFlags','Enable','off','HorizontalAlignment','center','TooltipString','Number of flagged events'});
controls.flagEvent=pair(1); controls.flagCount=pair(2);
buttons=section.addButtons('edit',{
    {'String','+ event','Callback',callbacks.addEvent,'KeyPressFcn',callbacks.keyPress,'TooltipString','Add/remove manual timestamps with cursor; saved to .added'}, ...
    {'String','+ interval','Callback',callbacks.addInterval,'KeyPressFcn',callbacks.keyPress,'TooltipString','Add intervals with cursor; saved to .added_intervals'}, ...
    {'String','- interval','Callback',callbacks.removeInterval,'KeyPressFcn',callbacks.keyPress,'TooltipString','Remove manually added intervals'}});
controls.addEvent=buttons(1); controls.addInterval=buttons(2); controls.removeInterval=buttons(3);
controls.saveEvent=section.addControl('save','pushbutton','String','Save events', ...
    'Callback',callbacks.saveEvent,'KeyPressFcn',callbacks.keyPress,'TooltipString','Save events to file');
end
