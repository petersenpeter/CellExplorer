function patch = detectMonoSyn(spikes, sr, settings)
%DETECTMONOSYN Legacy detector with explicit scientific settings, no UI or writes.
mono = ce_MonoSynConvClick(spikes,'sr',sr, ...
    'includeInhibitoryConnections',settings.includeInhibitoryConnections, ...
    'binSize',settings.binSize,'duration',settings.duration,'epoch',settings.epoch, ...
    'conv_w',settings.conv_w,'alpha',settings.alpha,'sigWindow',settings.sigWindow);
patch.data = ce.pipeline.monoSynAutomatic(mono);
end
