function [recording, file, stamp] = thetaRecording(session, hashContent)
%THETARECORDING Validate the existing int16 LFP and its acquisition metadata.
if nargin < 2, hashContent = true; end
file = fullfile(session.general.basePath,[session.general.name,'.lfp']);
if ~isfield(session,'channelTags') || ~isfield(session.channelTags,'Theta') || ...
        ~isfield(session.channelTags.Theta,'channels') || isempty(session.channelTags.Theta.channels)
    error('ce:pipeline:MissingThetaChannel','Define a one-based channelTags.Theta.channels entry.');
end
recording.channel = session.channelTags.Theta.channels(1);
fields = {'sr','srLfp','nChannels','leastSignificantBit'};
for name = fields
    if ~isfield(session.extracellular,name{1})
        error('ce:pipeline:InvalidThetaAcquisition','Theta requires extracellular.%s.',name{1});
    end
    value = session.extracellular.(name{1});
    if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ~isfinite(value) || value <= 0
        error('ce:pipeline:InvalidThetaAcquisition','Theta requires a positive finite extracellular.%s.',name{1});
    end
    recording.(name{1}) = value;
end
if recording.srLfp <= 22 || mod(recording.srLfp,5) ~= 0 || mod(recording.nChannels,1) ~= 0 || ...
        ~isnumeric(recording.channel) || ~isreal(recording.channel) || ~isfinite(recording.channel) || ...
        recording.channel < 1 || recording.channel > recording.nChannels || mod(recording.channel,1) ~= 0
    error('ce:pipeline:InvalidThetaAcquisition', ...
        'Theta needs a one-based integer channel and srLfp > 22 divisible by 5 for the legacy spectrogram window/overlap.');
end
info = dir(file);
if isempty(info) || info.isdir
    error('ce:pipeline:MissingThetaLfp','Create the LFP separately before theta processing: %s. No LFP will be generated by this stage.',file);
end
recording.nSamples = info.bytes/(2*recording.nChannels);
stamp = struct('bytes',info.bytes,'datenum',info.datenum);
if mod(recording.nSamples,1) ~= 0 || recording.nSamples < recording.srLfp
    error('ce:pipeline:InvalidThetaLfp','LFP must contain complete int16 channel frames and at least one second of data.');
end
recording.sha256 = '';
if hashContent
    recording.sha256 = ce.pipeline.fileFingerprint(file);
    after = dir(file);
    if isempty(after) || after.bytes ~= info.bytes || after.datenum ~= info.datenum
        error('ce:pipeline:ThetaLfpChanged','LFP changed while it was being fingerprinted.');
    end
end
end
