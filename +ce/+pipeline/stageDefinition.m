function definition = stageDefinition(name)
%STAGEDEFINITION Explicit outputs and implementation dependencies of migrated stages.
definition.name = name;
definition.version = 1;
switch name
    case 'monosynaptic_detection'
        definition.requiredOutputs = {'data'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.detectMonoSyn','ce.pipeline.prepareMonoSyn', ...
            'ce.pipeline.monoSynAutomatic','ce_MonoSynConvClick','ce_cch_conv', ...
            'generateSpinDices','ce_InIntervals','FindInInterval','CCG','CCGHeart', ...
            'isdscalar','isdvector','isdmatrix'};
    case 'monosynaptic_metrics'
        definition.requiredOutputs = {'putativeConnections','synapticEffect','synapticConnectionsOut','synapticConnectionsIn'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.monoSynMetrics','ce_GetTransProb','ce_cch_conv', ...
            'ce.curation.validateMonoSynSelection'};
    case 'waveform_extraction'
        definition.requiredOutputs = [strcat('data.',ce.pipeline.waveformFields), {'waveformParameters'}];
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.extractWaveforms','ce.pipeline.prepareWaveforms', ...
            'ce.pipeline.rawRecording','ce.pipeline.waveformFields','getWaveformsFromDat', ...
            'getBadChannelsFromDat','get_bad_channels','preferences_ProcessCellMetrics'};
    case 'waveform_localization'
        definition.requiredOutputs = {'trilat_x','trilat_y','peakVoltage_expFit','general.chanCoords'};
        definition.outputs = [definition.requiredOutputs, {'ccf_x','ccf_y','ccf_z','general.ccf'}];
        definition.dependencies = {'ce.pipeline.stages.localizeWaveforms','ce.pipeline.resolveGeometry', ...
            'ce.pipeline.localizationInputs','get_bad_channels','generateChanCoords','trilat','trilat3'};
    case 'waveform_shape'
        definition.requiredOutputs = {'waveforms.filt','waveforms.time','peakVoltage', ...
            'troughToPeak','troughtoPeakDerivative','ab_ratio','polarity'};
        definition.outputs = [definition.requiredOutputs, {'waveforms.filt_std', ...
            'waveforms.raw','waveforms.raw_std','waveforms.raw_all','waveforms.filt_all', ...
            'waveforms.time_all','waveforms.channels_all','waveforms.bestChannels', ...
            'waveforms.peakVoltage_all','peakVoltage_expFitLengthConstant'}];
        definition.dependencies = {'ce.pipeline.stages.waveformShape','ce.metrics.calc_waveform_metrics','get_bad_channels'};
    case 'acg_metrics'
        definition.requiredOutputs = {'acg.wide','acg.narrow','acg.log10','isi.log10', ...
            'general.acgs.log10','general.isis.log10','thetaModulationIndex', ...
            'burstIndex_Royer2012','burstIndex_Doublets','acg_tau_decay','acg_tau_rise', ...
            'acg_c','acg_d','acg_asymptote','acg_refrac','acg_fit_rsquare','acg_tau_burst','acg_h'};
        definition.outputs = [definition.requiredOutputs, {'responseCurves.meanCCG', ...
            'general.responseCurves.meanCCG','population_modIndex'}];
        definition.dependencies = {'ce.pipeline.stages.acgMetrics','calc_ACG_metrics','fit_ACG', ...
            'calc_logACGs','ce.metrics.calc_logISIs','detectDownStateCells','CCG','CCGHeart', ...
            'isToolboxInstalled','generateSpinDices','isdscalar','isdvector'};
    otherwise
        error('ce:pipeline:UnknownStage','No migrated stage definition for %s.',name);
end
definition.dependencies{end+1} = 'ce.pipeline.stageDefinition';
definition.dependencies{end+1} = 'ce.pipeline.stageInputs';
definition.dependencies{end+1} = 'ce.pipeline.stageSettings';
end
