function definition = stageDefinition(name, format)
%STAGEDEFINITION Explicit outputs and implementation dependencies of migrated stages.
definition.name = name;
definition.version = 1;
switch name
    case 'spike_import'
        definition.requiredOutputs = {'data'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.io.importNeurosuiteSpikes','ce.io.neurosuiteImportPlan', ...
            'ce.pipeline.spikeImportInputs','ce.pipeline.prepareSpikeImport','ce.pipeline.verifySpikeImport', ...
            'ce.pipeline.stages.importSpikes','ce.pipeline.spikeIdentityHash','ce.pipeline.spikeSortingRevision', ...
            'ce.data.validateSortingRevision','ce.pipeline.fileFingerprint'};
        if nargin>1 && strcmp(format,'phy')
            definition.dependencies=[definition.dependencies,{'ce.io.importPhySpikes', ...
                'ce.io.phyImportPlan','ce.io.readPhyLabels','ce.io.readSortingNpy','readNPY','readNPYheader','tdfread'}];
        end
    case 'cell_class_import'
        definition.requiredOutputs = {};
        definition.outputs = {'CellClassBuzcode'};
        definition.dependencies = {'ce.pipeline.cellClassInput','ce.data.cellIdentityOrder', ...
            'ce.pipeline.runCellClass','ce.pipeline.stages.cellClass'};
    case 'other_metrics'
        definition.requiredOutputs = {'spikeCount','firingRate','firingRateGiniCoeff','firingRateCV', ...
            'firingRateInstability','firingRateISI','cv2','burstIndex_Mizuseki2012', ...
            'refractoryPeriodViolation','responseCurves.firingRateAcrossTime', ...
            'general.responseCurves.firingRateAcrossTime'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.coreMetrics','ce.pipeline.runCoreMetrics','ce.metrics.calc_gini'};
    case 'deepSuperficial'
        definition.requiredOutputs = {'general.processinginfo.deepSuperficialProjection'};
        definition.outputs = [definition.requiredOutputs, {'general.SWR','general.deepSuperficial_file', ...
            'general.processinginfo.deepSuperficialfromRipple'}];
        definition.dependencies = {'ce.pipeline.deepSuperficialInput','ce.pipeline.runDeepSuperficial', ...
            'ce.pipeline.stages.deepSuperficial','ce.data.deepSuperficialChannels', ...
            'ce.curation.reconcileDeepSuperficial'};
    case 'theta_signal'
        definition.requiredOutputs = {'data'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.prepareTheta','ce.pipeline.thetaRecording', ...
            'ce.processing.instantaneousTheta','ce.io.readLfpChannel','nanconv','ce_gausswin'};
    case 'theta_metrics'
        definition.requiredOutputs = {'thetaPhasePeak','thetaPhaseTrough','thetaEntrainment', ...
            'responseCurves.thetaPhase','general.responseCurves.thetaPhase'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.thetaMetrics','ce.pipeline.runThetaStages', ...
            'ce.pipeline.thetaSpikes','ce.pipeline.thetaBehavior','nanconv'};
    case {'spatial_metrics','psth_metrics'}
        definition.dependencies = {'ce.pipeline.importedCellFiles','ce.pipeline.runImportedStages','ce.data.cellIdentityOrder'};
        if strcmp(name,'spatial_metrics')
            definition.requiredOutputs = {'firingRateMaps','general.firingRateMaps'};
            definition.outputs = [definition.requiredOutputs, {'spatialPeakRate','spatialCoherence', ...
                'placeCell','placeFieldsCount','spatialCoverageIndex','spatialGiniCoeff'}];
            definition.dependencies = [definition.dependencies, {'ce.pipeline.stages.spatialMetrics', ...
                'place_cell_condition','SpatialCoherence','nanconv','ce.metrics.calc_gini'}];
        else
            definition.requiredOutputs = {};
            definition.outputs = {};
            definition.dependencies{end+1} = 'ce.pipeline.stages.importedPsth';
        end
    case {'event_metrics','manipulation_metrics','state_metrics'}
        definition.requiredOutputs = {}; % Bound to the current named files by the planner.
        definition.outputs = {};
        definition.dependencies = {'ce.pipeline.intervalFiles','ce.pipeline.intervalOwnership', ...
            'ce.pipeline.intervalStagePlans','ce.pipeline.runIntervalStages'};
        if strcmp(name,'state_metrics')
            definition.dependencies = [definition.dependencies, {'ce.pipeline.stages.stateMetrics', ...
                'ce_InIntervals','FindInInterval','isdmatrix'}];
        else
            definition.dependencies = [definition.dependencies, {'ce.pipeline.stages.intervalResponses', ...
                'calc_PSTH','CCG','CCGHeart','isdscalar','isdvector','nanconv','ce_gausswin'}];
        end
    case 'monosynaptic_detection'
        definition.requiredOutputs = {'data'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.detectMonoSyn','ce.pipeline.prepareMonoSyn', ...
            'ce.pipeline.monoSynAutomatic','ce.data.validateSortingRevision','ce_MonoSynConvClick','ce_cch_conv', ...
            'generateSpinDices','ce_InIntervals','FindInInterval','CCG','CCGHeart', ...
            'isdscalar','isdvector','isdmatrix'};
    case 'monosynaptic_metrics'
        definition.requiredOutputs = {'putativeConnections','synapticEffect','synapticConnectionsOut','synapticConnectionsIn'};
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.monoSynMetrics','ce_GetTransProb','ce_cch_conv', ...
            'ce.curation.validateMonoSynSelection'};
    case 'waveform_extraction'
        definition.requiredOutputs = [strcat('data.',ce.pipeline.waveformFields), {'waveformParameters'}];
        definition.outputs = definition.requiredOutputs;
        definition.dependencies = {'ce.pipeline.stages.extractWaveforms','ce.pipeline.prepareWaveforms', ...
            'ce.pipeline.rawRecording','ce.pipeline.waveformFields','getWaveformsFromDat', ...
            'getBadChannelsFromDat','get_bad_channels','preferences_ProcessCellMetrics'};
    case 'waveform_localization'
        definition.requiredOutputs = {'trilat_x','trilat_y','peakVoltage_expFit','general.chanCoords'};
        definition.outputs = [definition.requiredOutputs, {'ccf_x','ccf_y','ccf_z','general.ccf'}];
        definition.dependencies = {'ce.pipeline.stages.localizeWaveforms','ce.pipeline.resolveGeometry', ...
            'ce.pipeline.localizationInputs','get_bad_channels','generateChanCoords','trilat','trilat3'};
    case 'waveform_shape'
        definition.requiredOutputs = {'waveforms.filt','waveforms.time','peakVoltage', ...
            'troughToPeak','troughtoPeakDerivative','ab_ratio','polarity'};
        definition.outputs = [definition.requiredOutputs, {'waveforms.filt_std', ...
            'waveforms.raw','waveforms.raw_std','waveforms.raw_all','waveforms.filt_all', ...
            'waveforms.time_all','waveforms.channels_all','waveforms.bestChannels', ...
            'waveforms.peakVoltage_all','peakVoltage_expFitLengthConstant'}];
        definition.dependencies = {'ce.pipeline.stages.waveformShape','ce.metrics.calc_waveform_metrics','get_bad_channels'};
    case 'acg_metrics'
        definition.requiredOutputs = {'acg.wide','acg.narrow','acg.log10','isi.log10', ...
            'general.acgs.log10','general.isis.log10','thetaModulationIndex', ...
            'burstIndex_Royer2012','burstIndex_Doublets','acg_tau_decay','acg_tau_rise', ...
            'acg_c','acg_d','acg_asymptote','acg_refrac','acg_fit_rsquare','acg_tau_burst','acg_h'};
        definition.outputs = [definition.requiredOutputs, {'responseCurves.meanCCG', ...
            'general.responseCurves.meanCCG','population_modIndex'}];
        definition.dependencies = {'ce.pipeline.stages.acgMetrics','calc_ACG_metrics','fit_ACG', ...
            'calc_logACGs','ce.metrics.calc_logISIs','detectDownStateCells','CCG','CCGHeart', ...
            'isToolboxInstalled','generateSpinDices','isdscalar','isdvector'};
    otherwise
        error('ce:pipeline:UnknownStage','No migrated stage definition for %s.',name);
end
definition.dependencies{end+1} = 'ce.pipeline.stageDefinition';
definition.dependencies{end+1} = 'ce.pipeline.stageInputs';
definition.dependencies{end+1} = 'ce.pipeline.stageSettings';
end
